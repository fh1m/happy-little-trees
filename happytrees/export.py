"""Turn a fitted decision tree into a C function a microcontroller can run.

    python -m happytrees.export > tree.h       # the CV-pruned tree from run.py

A pruned tree is a handful of if/else statements. There's no reason it
should need Python, NumPy or a model file on the robot.
"""

from __future__ import annotations

import sys

import numpy as np
from sklearn.tree import DecisionTreeClassifier


def to_c(clf: DecisionTreeClassifier, name: str = "predict", features: list[str] | None = None) -> str:
    t = clf.tree_
    feats = features or [f"x[{i}]" for i in range(clf.n_features_in_)]
    lines = [f"/* {clf.get_n_leaves()} leaves, depth {clf.get_depth()}; generated by happytrees.export */",
             f"static inline int {name}(const float *x) {{"]

    def walk(node: int, depth: int) -> None:
        pad = "    " * depth
        if t.children_left[node] == t.children_right[node]:  # leaf
            cls = int(np.argmax(t.value[node][0]))
            lines.append(f"{pad}return {int(clf.classes_[cls])};")
            return
        lines.append(f"{pad}if ({feats[t.feature[node]]} <= {t.threshold[node]:.9g}f) {{")
        walk(t.children_left[node], depth + 1)
        lines.append(f"{pad}}} else {{")
        walk(t.children_right[node], depth + 1)
        lines.append(f"{pad}}}")

    walk(0, 1)
    lines.append("}")
    return "\n".join(lines) + "\n"


def pruned_tree() -> DecisionTreeClassifier:
    from sklearn.model_selection import cross_val_score

    from .run import SEED, data

    Xtr, _, ytr, _ = data()
    path = DecisionTreeClassifier(random_state=SEED).cost_complexity_pruning_path(Xtr, ytr)
    alphas = path.ccp_alphas[:-1]
    cv = [cross_val_score(DecisionTreeClassifier(ccp_alpha=a, random_state=SEED), Xtr, ytr, cv=5).mean()
          for a in alphas]
    return DecisionTreeClassifier(ccp_alpha=float(alphas[int(np.argmax(cv))]), random_state=SEED).fit(Xtr, ytr)


if __name__ == "__main__":
    sys.stdout.write(to_c(pruned_tree()))
